using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using Volco.Audio;
using Volco.Config;
using static Volco.UI.ViewModels.DeviceRefLookup;

namespace Volco.UI.ViewModels;

/// <summary>
/// ViewModel for a single slider entry in the Sliders settings tab.
/// Wraps a <see cref="SliderConfig"/> slice and persists on every property change.
/// </summary>
public partial class SliderItemViewModel : ObservableObject
{
    private readonly SliderConfig _cfg;
    private readonly IAudioEngine _audio;
    private readonly Action _save;

    // ── Backing fields generated by [ObservableProperty] ──────────────────────

    [ObservableProperty]
    private SliderMappingType _mappingType;

    [ObservableProperty]
    private string _processesText = "";

    [ObservableProperty]
    private string _deviceName = "";

    [ObservableProperty]
    private bool _invert;

    [ObservableProperty]
    private ResponseCurve _curve;

    [ObservableProperty]
    private double _deadZonePercent;

    [ObservableProperty]
    private double _smoothingFactor;

    /// <summary>
    /// Live volume level 0..1. Wired to real data in Task 11; defaults to 0 here.
    /// </summary>
    [ObservableProperty]
    private double _liveLevel;

    [ObservableProperty]
    private bool _isExpanded = true;

    [RelayCommand]
    private void ToggleExpanded() => IsExpanded = !IsExpanded;

    // ── ComboBox index helpers (x:Bind TwoWay to SelectedIndex) ─────────────

    /// <summary>
    /// Zero-based index for the MappingType ComboBox.
    /// Order matches XAML items: 0=Processes, 1=Device, 2=Unmapped.
    /// </summary>
    public int MappingTypeIndex
    {
        get => MappingType switch
        {
            SliderMappingType.Processes => 0,
            SliderMappingType.Device    => 1,
            SliderMappingType.Unmapped  => 2,
            _                           => 1,
        };
        set => MappingType = value switch
        {
            0 => SliderMappingType.Processes,
            1 => SliderMappingType.Device,
            2 => SliderMappingType.Unmapped,
            _ => SliderMappingType.Device,
        };
    }

    /// <summary>
    /// Zero-based index for the ResponseCurve ComboBox.
    /// Order matches XAML items: 0=Linear, 1=Logarithmic, 2=Exponential, 3=S-Curve.
    /// </summary>
    public int CurveIndex
    {
        get => Curve switch
        {
            ResponseCurve.Linear      => 0,
            ResponseCurve.Logarithmic => 1,
            ResponseCurve.Exponential => 2,
            ResponseCurve.SCurve      => 3,
            _                         => 0,
        };
        set => Curve = value switch
        {
            0 => ResponseCurve.Linear,
            1 => ResponseCurve.Logarithmic,
            2 => ResponseCurve.Exponential,
            3 => ResponseCurve.SCurve,
            _ => ResponseCurve.Linear,
        };
    }

    // ── Read-only ─────────────────────────────────────────────────────────────

    public int Index { get; }

    // ── Derived visibility helpers (bool; views convert to Visibility) ─────────

    public bool IsProcessesVisible => MappingType == SliderMappingType.Processes;
    public bool IsDeviceVisible => MappingType == SliderMappingType.Device;
    public bool IsUnmapped => MappingType == SliderMappingType.Unmapped;

    /// <summary>
    /// Available output devices; populated from IAudioEngine when the VM is constructed.
    /// </summary>
    public ObservableCollection<AudioDevice> OutputDevices { get; } = new();

    /// <summary>
    /// Output device names for binding to ComboBox.ItemsSource (string list).
    /// Mirrors <see cref="OutputDevices"/> as plain strings so SelectedItem can
    /// bind directly to <see cref="DeviceName"/>.
    /// </summary>
    public List<string> OutputDeviceNames { get; private set; } = new();

    // ── Constructor ───────────────────────────────────────────────────────────

    public SliderItemViewModel(SliderConfig cfg, IAudioEngine audio, IReadOnlyList<AudioDevice> outputDevices, Action save)
    {
        _cfg = cfg;
        _audio = audio;
        _save = save;

        Index = cfg.Index;
        _mappingType = cfg.Type;
        // Processes stored as List<string>; display as comma-separated.
        _processesText = string.Join(", ", cfg.Processes);
        _deviceName = cfg.Device?.FriendlyName ?? "";
        _invert = cfg.Invert;
        _curve = cfg.Curve;
        _deadZonePercent = cfg.DeadZonePercent;
        _smoothingFactor = cfg.SmoothingFactor;

        foreach (var d in outputDevices)
            OutputDevices.Add(d);
        OutputDeviceNames = OutputDevices.Select(d => d.FriendlyName).ToList();
    }

    // ── Generated partial hooks — write back to cfg and save ──────────────────

    partial void OnMappingTypeChanged(SliderMappingType value)
    {
        _cfg.Type = value;
        OnPropertyChanged(nameof(IsProcessesVisible));
        OnPropertyChanged(nameof(IsDeviceVisible));
        OnPropertyChanged(nameof(IsUnmapped));
        OnPropertyChanged(nameof(MappingTypeIndex));
        Persist();
    }

    partial void OnProcessesTextChanged(string value)
    {
        _cfg.Processes = value
            .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .ToList();
        Persist();
    }

    partial void OnDeviceNameChanged(string value)
    {
        _cfg.Device = DeviceRefFromName(value);
        Persist();
    }

    partial void OnInvertChanged(bool value)
    {
        _cfg.Invert = value;
        Persist();
    }

    partial void OnCurveChanged(ResponseCurve value)
    {
        _cfg.Curve = value;
        OnPropertyChanged(nameof(CurveIndex));
        Persist();
    }

    partial void OnDeadZonePercentChanged(double value)
    {
        _cfg.DeadZonePercent = value;
        Persist();
    }

    partial void OnSmoothingFactorChanged(double value)
    {
        _cfg.SmoothingFactor = value;
        Persist();
    }

    // LiveLevel changes do NOT trigger a save — it's a transient display value.

    /// <summary>Returns process-name suggestions matching the last typed token.</summary>
    public List<string> GetProcessSuggestions(string currentText)
    {
        var parts = currentText.Split(',');
        var lastPart = parts.LastOrDefault()?.Trim() ?? "";
        if (string.IsNullOrEmpty(lastPart))
            return new List<string>();

        return _audio.GetSessions()
            .Select(s => s.ImageName)
            .Where(n => !string.IsNullOrEmpty(n))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Where(p => p.Contains(lastPart, StringComparison.OrdinalIgnoreCase))
            .ToList();
    }

    private void Persist() => _save();
}
