// Generates tools/simulator/volco_config_descriptor.js, the protobufjs JSON descriptor of
// proto/volco_config.proto, as a script (the simulator opens from file://, where fetch fails).
//   cd tools/simulator/test && npm ci && node gen_descriptor.mjs
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const require = createRequire(import.meta.url);
const protobuf = require('protobufjs');
const here = path.dirname(fileURLToPath(import.meta.url));
const proto = path.join(here, '..', '..', '..', 'proto', 'volco_config.proto');
const out = path.join(here, '..', 'volco_config_descriptor.js');

const root = protobuf.loadSync(proto);
const json = JSON.stringify(root.toJSON(), null, 1);
fs.writeFileSync(out,
  '// Generated by tools/simulator/test/gen_descriptor.mjs from proto/volco_config.proto; do not edit.\n' +
  `(function (root) {\n  const descriptor = ${json.replace(/\n/g, '\n  ')};\n` +
  "  if (typeof module === 'object' && module.exports) module.exports = descriptor;\n" +
  '  else root.VOLCO_CONFIG_DESCRIPTOR = descriptor;\n' +
  "})(typeof globalThis !== 'undefined' ? globalThis : this);\n");
console.log(`wrote ${out}`);
