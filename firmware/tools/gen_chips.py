#!/usr/bin/env python3
"""Generates the chip tables (docs/design/arduino-avr.md §4) from proto/chips.json:
firmware/lib/volco_config/src/volco_chip_table.cpp, src/Volco.Core/Controller/ChipInfo.g.cs and
tools/simulator/chips.js. Any Python 3, no packages. CI regenerates and fails on a difference."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCE = os.path.join(ROOT, "proto", "chips.json")
CPP = os.path.join(ROOT, "firmware", "lib", "volco_config", "src", "volco_chip_table.cpp")
CS = os.path.join(ROOT, "src", "Volco.Core", "Controller", "ChipInfo.g.cs")
JS = os.path.join(ROOT, "tools", "simulator", "chips.js")
HEADER = "Generated by firmware/tools/gen_chips.py from proto/chips.json. Do not edit."
SETS = ("exists", "reserved", "inputOnly", "adc1", "adc2")


def pins(spec):
    out = set()
    for item in spec:
        if isinstance(item, int):
            out.add(item)
        else:
            m = re.fullmatch(r"(\d+)-(\d+)", item)
            if not m:
                raise SystemExit(f"bad pin range {item!r}")
            out.update(range(int(m.group(1)), int(m.group(2)) + 1))
    if any(p < 0 or p > 63 for p in out):
        raise SystemExit(f"pins must be 0-63: {sorted(out)}")
    return sorted(out)


def mask(ps):
    return sum(1 << p for p in ps)


def load():
    with open(SOURCE, encoding="utf-8") as f:
        chips = json.load(f)["chips"]
    for c in chips:
        for s in SETS:
            c[s] = pins(c.get(s, []))
    return chips


def pascal(key):
    return key[:1].upper() + key[1:]


def cpp(chips):
    lines = [f"// {HEADER}", '#include "volco_chip.h"', "", "namespace volco {", "namespace {"]
    for c in chips:
        args = ", ".join(f"0x{mask(c[s]):016X}ull" for s in SETS)
        lines.append(f"constexpr ChipInfo k{pascal(c['key'])}{{{args}}};  // {c['name']}")
    lines += ["}  // namespace", ""]
    for c in chips:
        lines.append(f"const ChipInfo& {c['key']}Chip() {{ return k{pascal(c['key'])}; }}")
    lines += ["", "}  // namespace volco", ""]
    return "\n".join(lines)


def cs(chips):
    lines = [f"// <auto-generated>{HEADER}</auto-generated>", "namespace Volco.Core.Controller;", "",
             "public sealed partial class ChipInfo", "{"]
    for c in chips:
        args = ", ".join(f"0x{mask(c[s]):016X}UL" for s in SETS)
        lines.append(f"    /// <summary>{c['name']} (Hello chip {c['id']}).</summary>")
        lines.append(f"    public static ChipInfo {pascal(c['key'])} {{ get; }} = new({args});")
    lines += ["}", ""]
    return "\n".join(lines)


def js(chips):
    body = []
    for c in chips:
        fields = [f"id: {c['id']}", f"key: '{c['key']}'", f"name: '{c['name']}'"]
        fields += [f"{s}: [{', '.join(map(str, c[s]))}]" for s in SETS]
        body.append(f"    {c['key']}: {{\n      " + ",\n      ".join(fields) + ",\n    },")
    return "\n".join([
        f"// {HEADER}",
        "// Classic script: index.html loads it as globalThis.VolcoChips, the Node tests with require().",
        "(function (root) {",
        "  'use strict';",
        "  const chips = {",
        *body,
        "  };",
        "  if (typeof module === 'object' && module.exports) module.exports = chips;",
        "  else root.VolcoChips = chips;",
        "})(typeof globalThis !== 'undefined' ? globalThis : this);",
        "",
    ])


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    chips = load()
    write(CPP, cpp(chips))
    write(CS, cs(chips))
    write(JS, js(chips))
    print(f"{len(chips)} chip(s) written")


if __name__ == "__main__":
    main()
